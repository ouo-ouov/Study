/*
	자료형 변환
	- 값 종류 변환 의미와 같다.
	- 데이터 종류 변환 의미와 같다.
	- 데이터형 변환 의미와 같다.
	
	- 값의 종류를 변경한다.
	 10   -> 10.0
	 10.9 -> 10
	 "10" -> 10
	 
	- 값의 종류를 변경하는 방법 2가지
	
	 	방법1. + 연산을 하기 전에 각 값을 자동으로 변환시키는 방법 (암시적(자동) 형변환)
	 	
	 		"123" + 1
	 		
	 		순서1. 숫자가 자동으로 문자열로 변환됩니다.
	 		     "1"
	 		     
	 		순서2. "문자열" + "숫자" <- 드디어 합칩니다.
	 			      "1231"
	 	
	 	방법2. 개발자가 값을 직접 변환시키는 방법 (명시적(강제) 형변환)
	 	
	 		128.123123123123123 실수값을 무조건!! 128정수로 만들어서 사용해야 한다.
	 		
	 	    (변환할자료형_종류)128.123123123
	 			     (INT)128.123123123 -> 128
*/	

public class Date05 {

	public static void main(String[] args) {
		
		byte  a = 1;     // 1byte 크기의 변수a 만들어 정수 1 저장
		short b = 128;   // 2byte 크기의 변수b 만들어 정수 128 저장
		int   c = 32768; // 4byte 크기의 변수c 만들어 점수 32768 저장
		
		b = a;
		System.out.println("자동 형변환 결과 (b): " + b); //정상적으로 1 출력
		
		b = (short)c;
		System.out.println("강제 형변환 결과 (b): " + b); //오버플로우가 발생하여
													 //-32768 출력

	}

}
